import { createClient, type QueryParams } from "@sanity/client";
import { projectId, dataset, apiVersion } from "./env";
import "./types"; // registers each defineQuery's result type with the client (generated by `npm run typegen`)

/** Read client. Pages are built ahead of time, so read straight from the API (no CDN lag) at build. */
export const client = createClient({ projectId, dataset, apiVersion, useCdn: false, perspective: "published" });

/** Fetch a defineQuery query; the result type comes from the generated types for that exact query. */
export const sanityFetch = <const Q extends string>(query: Q, params: QueryParams = {}) => client.fetch(query, params);
